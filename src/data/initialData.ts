export const CITY_LOCATIONS: CityLocation[] = (() => {
  const dynamicLocs = WorldEngine.getCityLocations();
  const existingIds = new Set(BASE_CITY_LOCATIONS.map((l) => l.id));
  const uniqueDynamic = dynamicLocs.filter((l) => !existingIds.has(l.id));
  return [...BASE_CITY_LOCATIONS, ...uniqueDynamic];
})();

